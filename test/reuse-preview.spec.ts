import { test, expect } from "@playwright/test";
import JSZip from "jszip";
import { readFile } from "node:fs/promises";

test("isolated preview: 50 photos, submission files, matching, ZIP, search and backup", async ({ page, context }) => {
  const external: string[] = [], apiRequests: string[] = [], errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await context.route("**/*", route => {
    const url = route.request().url();
    if (/^https?:/.test(url) && !url.startsWith("http://127.0.0.1:4173/")) { external.push(url); return route.abort(); }
    if (/\/api\/|\/\.netlify\/functions\//.test(url)) { apiRequests.push(url); return route.abort(); }
    return route.continue();
  });
  await page.goto("/#careers");
  await expect(page.getByText("미리보기용 수업 나눔", { exact: true }).first()).toBeVisible();
  const originals = await page.evaluate(() => Array.from({ length: 50 }, (_, index) => {
    const canvas = document.createElement("canvas"); canvas.width = 160; canvas.height = 120;
    const ctx = canvas.getContext("2d")!; ctx.fillStyle = `hsl(${index * 7},40%,75%)`; ctx.fillRect(0,0,160,120); ctx.fillStyle = "#111"; ctx.fillText(`SYNTHETIC ${index}`, 12, 60);
    return canvas.toDataURL("image/png").split(",")[1];
  }));
  const files = originals.map((base64, index) => ({ name: `${index < 25 ? "모둠 토의" : "학습지 쓰기"}-${index}.png`, mimeType: "image/png", buffer: Buffer.from(base64, "base64") }));
  await page.getByRole("button", { name: /^사진 보관함/ }).click();
  await expect(page.getByRole("heading", { name: /사진 보관함/ })).toBeVisible();
  await page.getByLabel("사진 끌어 놓기", { exact: true }).setInputFiles(files);
  await expect(page.getByText("50장 추가, 동일 파일 0장 제외", { exact: true })).toBeVisible({ timeout: 60000 });
  await expect(page.locator(".reuse-photo")).toHaveCount(50);
  await page.getByLabel("사진 끌어 놓기", { exact: true }).setInputFiles(files.slice(0,2));
  await expect(page.getByText("0장 추가, 동일 파일 2장 제외", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "표시된 사진 선택", exact: true }).click();
  await page.getByRole("button", { name: "검토 완료", exact: true }).click();
  await expect(page.getByText("선택한 사진을 정리했습니다.", { exact: true })).toBeVisible();
  await expect(page.locator(".reuse-photo .confirmed")).toHaveCount(50);
  await page.getByRole("button", { name: "모둠 토의-0.png", exact: true }).click();
  await page.getByRole("textbox", { name: "장면 설명", exact: true }).fill("예시 모둠 토의 장면");
  await page.getByRole("button", { name: "사진 저장", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: /^공모전 제출본/ }).click();
  await page.getByRole("button", { name: "제출본 추가", exact: true }).click();
  await page.getByLabel("보고서와 첨부 파일 넣기", { exact: true }).setInputFiles({ name: "예시_연구보고서.txt", mimeType: "text/plain", buffer: Buffer.from("테스트용 보고서입니다. 실제 개인정보를 포함하지 않습니다.") });
  await expect(page.getByLabel("제출본 제목", { exact: true })).toHaveValue("예시_연구보고서");
  await page.getByLabel("공모전 또는 연구대회", { exact: true }).fill("예시 연구대회");
  await page.getByLabel("연도", { exact: true }).fill("2026");
  await page.getByLabel("상태", { exact: true }).selectOption("submitted");
  await page.getByLabel("제출일", { exact: true }).fill("2026-10-25");
  await page.getByRole("button", { name: "공고로 사진 찾기", exact: true }).click();
  await page.getByLabel("공고 또는 작성 양식 읽기", { exact: true }).setInputFiles({ name: "공고.txt", mimeType: "text/plain", buffer: Buffer.from("모둠 토의 사진\n학습지 쓰기 사진") });
  await expect(page.getByLabel("공고 내용 또는 필요한 사진 장면")).toHaveValue("모둠 토의 사진\n학습지 쓰기 사진");
  await page.getByRole("button", { name: "사진 자리 찾기", exact: true }).click();
  await expect(page.locator(".reuse-slot")).toHaveCount(2);
  await expect(page.locator(".reuse-candidates").first().locator(".reuse-candidate")).toHaveCount(6);
  await page.screenshot({ path: "/workspace/artifacts/reuse-matching-preview.png", fullPage: true });
  await page.getByLabel("사진 자리 1 직접 선택").selectOption({ label: "모둠 토의-0.png" });
  await page.getByRole("textbox", { name: "이 제출본의 사진 설명", exact: true }).fill("이번 제출본에 보관하는 설명");
  await page.getByLabel("사진 자리 2 직접 선택").selectOption({ label: "학습지 쓰기-25.png" });
  await page.getByRole("button", { name: "제출본 저장", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.reload();
  await page.getByRole("button", { name: /예시 연구대회.*예시_연구보고서/ }).click();
  await expect(page.locator(".submission-files")).toContainText("예시_연구보고서.txt");
  await page.getByRole("button", { name: "공고로 사진 찾기", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "이 제출본의 사진 설명", exact: true }).first()).toHaveValue("이번 제출본에 보관하는 설명");
  const zipEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "사진 ZIP", exact: true }).click();
  const zip = await JSZip.loadAsync(await readFile((await (await zipEvent).path())!));
  const zipPhotos = Object.values(zip.files).filter(file => file.name.endsWith(".png"));
  expect(zipPhotos).toHaveLength(2);
  expect(await zipPhotos[0].async("nodebuffer")).toEqual(files[0].buffer);
  expect(await zipPhotos[1].async("nodebuffer")).toEqual(files[25].buffer);
  expect(await zip.file("사진_설명.txt")!.async("string")).toContain("이번 제출본에 보관하는 설명");
  await page.getByRole("button", { name: "닫기", exact: true }).last().click();
  await page.goto("/#photos"); await page.reload();
  await expect(page.locator(".reuse-usage").first()).toContainText("예시 연구대회");
  await page.getByRole("button", { name: "모둠 토의-0.png", exact: true }).click();
  await expect(page.getByRole("button", { name: "삭제", exact: true })).toBeDisabled();
  await page.getByRole("textbox", { name: "장면 설명", exact: true }).fill("바뀐 사진 설명");
  await page.getByRole("button", { name: "사진 저장", exact: true }).click();
  await page.goto("/#settings"); await page.reload();
  const backupEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "전체 기록 JSON 내보내기", exact: true }).click();
  const backupBytes = await readFile((await (await backupEvent).path())!);
  const backup = JSON.parse(backupBytes.toString());
  expect(backup.workspace.items.filter((item: any) => item.kind === "photo")).toHaveLength(50);
  expect(backup.workspace.items.find((item: any) => item.kind === "submission").slots[0].caption).toBe("이번 제출본에 보관하는 설명");
  expect(backup.careers[0].title).toBe("미리보기용 수업 나눔");
  expect(backup.workspace.items.find((item: any) => item.kind === "project").title).toBe("미리보기용 우리 동네 탐구");
  await page.getByLabel("가져올 전체 기록 JSON", { exact: true }).setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: backupBytes });
  await page.getByRole("button", { name: "현재 기록에 추가", exact: true }).click();
  await expect(page.getByText(/학습 기록 0개, 연결 0개를 추가/)).toBeVisible();
  await page.goto("/#photos"); await page.reload();
  await page.getByLabel("사진 검색", { exact: true }).fill("학습지 쓰기-25");
  await expect(page.locator(".reuse-photo")).toHaveCount(1);
  await expect(page.locator(".reuse-photo img")).toBeVisible();
  await page.screenshot({ path: "/workspace/artifacts/reuse-photo-preview.png", fullPage: true });
  await page.getByRole("button", { name: "모든 기록 검색 열기", exact: true }).click();
  await page.getByLabel("모든 기록 검색어", { exact: true }).fill("예시_연구보고서");
  await page.getByLabel("검색할 기록 종류", { exact: true }).selectOption("submission");
  await page.getByRole("option", { name: /예시_연구보고서/ }).click();
  await expect(page.getByRole("dialog", { name: "공모전 제출본", exact: true })).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "삭제", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.locator(".submission-card")).toHaveCount(0);
  await page.goto("/#photos"); await page.reload();
  await page.getByRole("button", { name: "모둠 토의-0.png", exact: true }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "삭제", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.locator(".reuse-photo")).toHaveCount(49);
  await page.getByLabel("사진 끌어 놓기", { exact: true }).setInputFiles(files.slice(0,1));
  await expect(page.locator(".reuse-photo")).toHaveCount(50);
  expect(external).toEqual([]); expect(apiRequests).toEqual([]); expect(errors).toEqual([]);
});
